using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Probe.Changes.Gen;

// Prototype of the Tarol.Changes generator (candidate A). Per change record: the Target member. Per compilation: a typed
// dispatcher (object -> Run, for sagas/outbox), the reaction table (own events -> change, after commit), and - when
// ASP.NET Core is referenced - HTTP entries as RequestDelegates (style "request-delegate") or as MapPost(pattern, lambda)
// (style "delegate", to measure what the Request Delegate Generator does with generated calls).
[Generator(LanguageNames.CSharp)]
public sealed class ChangesGenerator : IIncrementalGenerator
{
    private const string ChangeIface = "Tarol.Changes.IChange`1";
    private const string CreationIface = "Tarol.Changes.ICreation`1";

    private static readonly DiagnosticDescriptor NoTarget = new("TCHG001", "Change has no single target id",
        "'{0}' needs exactly one Id<{1}> member to be its Target, found {2}; implement Target explicitly", "Tarol.Changes",
        DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var changes = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is RecordDeclarationSyntax { BaseList: not null } r && r.BaseList.Types.Any(
                    t => t.Type is GenericNameSyntax { Identifier.ValueText: "IChange" or "ICreation" }
                         || t.Type is QualifiedNameSyntax { Right: GenericNameSyntax { Identifier.ValueText: "IChange" or "ICreation" } }),
                static (ctx, ct) => Model.From((INamedTypeSymbol)ctx.SemanticModel.GetDeclaredSymbol(ctx.Node, ct)!, ctx.SemanticModel.Compilation))
            .Where(static m => m is not null)
            .Select(static (m, _) => m!)
            .WithTrackingName("ChangeModels");

        context.RegisterSourceOutput(changes, static (spc, m) =>
        {
            if (m.TargetCount != 1 && !m.UserTarget)
            {
                spc.ReportDiagnostic(Diagnostic.Create(NoTarget, null, m.Name, m.AggregateName, m.TargetCount));
                return;
            }
            if (m.UserTarget) return;
            var iface = m.IsCreation ? "ICreation" : "IChange";
            spc.AddSource($"{m.Name}.Change.g.cs", $$"""
                // <auto-generated/>
                #nullable enable
                namespace {{m.Namespace}};
                partial record {{m.Name}}
                {
                    global::Tarol.StronglyTypedId.Id<{{m.Aggregate}}> global::Tarol.Changes.{{iface}}<{{m.Aggregate}}>.Target => {{m.TargetMember}};
                }
                """);
        });

        var all = changes.Collect();
        var web = context.CompilationProvider.Select(static (c, _) =>
            c.GetTypeByMetadataName("Microsoft.AspNetCore.Routing.IEndpointRouteBuilder") is not null);
        var style = context.AnalyzerConfigOptionsProvider.Select(static (o, _) =>
            o.GlobalOptions.TryGetValue("build_property.ProbeEndpointStyle", out var s) && s == "delegate" ? "delegate" : "request-delegate");
        var ns = context.CompilationProvider.Select(static (c, _) => c.AssemblyName ?? "App");

        context.RegisterSourceOutput(all.Combine(ns), static (spc, pair) => spc.AddSource("Changes.Dispatch.g.cs", Emit.Dispatch(pair.Left, pair.Right)));
        context.RegisterSourceOutput(all.Combine(web).Combine(style), static (spc, pair) =>
        {
            if (!pair.Left.Right) return;
            spc.AddSource("Changes.Endpoints.g.cs", Emit.Endpoints(pair.Left.Left, pair.Right));
        });
    }

    internal sealed record Member(string Name, string Type, bool IsId);
    internal sealed record Reaction(string Event, string Method);
    internal sealed record Hook(string Sender, string Type, string Payload, string Method);

    internal sealed record Model(string Namespace, string Name, string Aggregate, string AggregateName, bool IsCreation,
        string? TargetMember, int TargetCount, bool UserTarget, Eq<Member> Members, string? Route, string? Policy,
        Eq<Reaction> Reactions, Eq<Hook> Webhooks)
    {
        public string Full => $"global::{Namespace}.{Name}";

        public static Model? From(INamedTypeSymbol type, Compilation compilation)
        {
            var change = compilation.GetTypeByMetadataName(ChangeIface);
            var creation = compilation.GetTypeByMetadataName(CreationIface);
            var iface = type.AllInterfaces.FirstOrDefault(i =>
                SymbolEqualityComparer.Default.Equals(i.OriginalDefinition, change) ||
                SymbolEqualityComparer.Default.Equals(i.OriginalDefinition, creation));
            if (iface is null) return null;
            var aggregate = iface.TypeArguments[0];
            var fq = SymbolDisplayFormat.FullyQualifiedFormat;
            var idName = $"global::Tarol.StronglyTypedId.Id<{aggregate.ToDisplayString(fq)}>";
            var props = type.GetMembers().OfType<IPropertySymbol>().Where(p => !p.IsStatic && p.DeclaredAccessibility == Accessibility.Public && p.Name != "EqualityContract").ToArray();
            var ids = props.Where(p => p.Type.ToDisplayString(fq) == idName).ToArray();
            var userTarget = type.GetMembers().Any(m => m is IPropertySymbol && (m.Name == "Target" || m.Name.EndsWith(".Target", StringComparison.Ordinal)));
            string? route = null, policy = null;
            foreach (var a in type.GetAttributes())
                if (a.AttributeClass?.ToDisplayString() == "Tarol.Changes.EndpointAttribute")
                {
                    route = a.ConstructorArguments[0].Value as string;
                    policy = a.NamedArguments.FirstOrDefault(n => n.Key == "Policy").Value.Value as string;
                }
            var reactions = new List<Reaction>();
            var hooks = new List<Hook>();
            foreach (var m in type.GetMembers().OfType<IMethodSymbol>().Where(m => m.IsStatic))
                foreach (var a in m.GetAttributes())
                {
                    var name = a.AttributeClass?.OriginalDefinition.ToDisplayString();
                    if (name == "Tarol.Changes.OnEventAttribute<TEvent>")
                        reactions.Add(new Reaction(a.AttributeClass!.TypeArguments[0].ToDisplayString(fq), m.Name));
                    else if (name == "Tarol.Changes.WebhookAttribute")
                        hooks.Add(new Hook((string)a.ConstructorArguments[0].Value!, (string)a.ConstructorArguments[1].Value!, m.Parameters[0].Type.ToDisplayString(fq), m.Name));
                }
            return new Model(type.ContainingNamespace.ToDisplayString(), type.Name, aggregate.ToDisplayString(fq), aggregate.Name,
                SymbolEqualityComparer.Default.Equals(iface.OriginalDefinition, creation), ids.Length == 1 ? ids[0].Name : null,
                ids.Length, userTarget,
                new Eq<Member>(props.Select(p => new Member(p.Name, p.Type.ToDisplayString(fq), p.Type.ToDisplayString(fq) == idName))),
                route, policy, new Eq<Reaction>(reactions), new Eq<Hook>(hooks));
        }
    }
}

/// <summary>Value-equal array for incremental models (no locations, no symbols).</summary>
internal readonly struct Eq<T>(IEnumerable<T> items) : IEquatable<Eq<T>>
{
    private readonly ImmutableArray<T> _items = items.ToImmutableArray();
    public ImmutableArray<T> Items => _items.IsDefault ? ImmutableArray<T>.Empty : _items;
    public bool Equals(Eq<T> other) => Items.SequenceEqual(other.Items);
    public override bool Equals(object? obj) => obj is Eq<T> o && Equals(o);
    public override int GetHashCode() => Items.Aggregate(17, (h, i) => h * 31 + (i?.GetHashCode() ?? 0));
}
