using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace Probe.Changes.Gen;

internal static class Emit
{
    public static string Dispatch(ImmutableArray<ChangesGenerator.Model> models, string assembly)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>\n#nullable enable\nnamespace Tarol.Changes.Generated;\n");
        sb.AppendLine("/// <summary>Typed entries of this assembly's changes: no reflection, no object dispatch at run time.</summary>");
        sb.AppendLine("public static class GeneratedChanges\n{");
        // object -> typed Run: what a saga outbox row or a test harness needs
        sb.AppendLine("    public static global::System.Threading.Tasks.ValueTask<global::Tarol.Results.Result<global::Tarol.Changes.ChangeOutcome>> Dispatch(this global::Tarol.Changes.ChangePipeline pipeline, object change, global::Tarol.Kernel.OperationContext context, global::Tarol.Changes.ChangeOptions options = default, global::System.Threading.CancellationToken cancellationToken = default)");
        sb.AppendLine("        => change switch\n        {");
        foreach (var m in models.OrderBy(m => m.Name))
            sb.AppendLine($"            {m.Full} c => pipeline.Run(c, context, options, cancellationToken),");
        sb.AppendLine("            _ => throw new global::System.ArgumentException($\"{change.GetType().Name} is not a change of " + assembly + ".\", nameof(change)),\n        };\n");

        // reactions: names for the outbox writer, and the run per name
        var reactions = models.SelectMany(m => m.Reactions.Items.Select(r => (m, r))).OrderBy(x => x.m.Name).ToArray();
        sb.AppendLine("    /// <summary>The reactions to an own event: one outbox row each, written in the commit's transaction.</summary>");
        sb.AppendLine("    public static global::System.Collections.Generic.IReadOnlyList<string> ReactionsTo(global::Tarol.Primitives.DomainEvent domainEvent) => domainEvent switch\n    {");
        var groups = reactions.GroupBy(x => x.r.Event).ToArray();   // index, not GetHashCode: string hashes differ per process
        for (var i = 0; i < groups.Length; i++)
            sb.AppendLine($"        {groups[i].Key} => __reactions{i},");
        sb.AppendLine("        _ => [],\n    };\n");
        for (var i = 0; i < groups.Length; i++)
            sb.AppendLine($"    private static readonly string[] __reactions{i} = [{string.Join(", ", groups[i].Select(x => $"\"{x.m.Name}\""))}];");
        sb.AppendLine("    /// <summary>Runs one reaction to a committed event: system actor, caused by the event, keyed by event id + reaction.</summary>");
        sb.AppendLine("    public static global::System.Threading.Tasks.ValueTask<global::Tarol.Results.Result<global::Tarol.Changes.ChangeOutcome>> React(this global::Tarol.Changes.ChangePipeline pipeline, string reaction, global::Tarol.Primitives.RecordedEvent recorded, global::System.Threading.CancellationToken cancellationToken = default)\n    {");
        sb.AppendLine("        var context = recorded.Context.AsSystem(\"Reactions.\" + reaction).CausedBy((global::Tarol.StronglyTypedId.Id<global::Tarol.Kernel.ICausation>)recorded.EventId);");
        sb.AppendLine("        var key = new global::Tarol.Changes.IdempotencyKey(recorded.Context.Tenant, reaction, recorded.EventId.ToString(\"N\"));");
        sb.AppendLine("        var options = new global::Tarol.Changes.ChangeOptions(Key: key);");
        sb.AppendLine("        return (reaction, recorded.Event.Event) switch\n        {");
        foreach (var (m, r) in reactions)
            sb.AppendLine($"            (\"{m.Name}\", {r.Event} e) => pipeline.Run({m.Full}.{r.Method}(e, recorded), context, options, cancellationToken),");
        sb.AppendLine("            _ => throw new global::System.ArgumentException($\"No reaction {reaction} to {recorded.Event.Event.GetType().Name}.\", nameof(reaction)),\n        };\n    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string Endpoints(ImmutableArray<ChangesGenerator.Model> models, string style)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>\n#nullable enable\nusing Microsoft.AspNetCore.Builder;\nusing Microsoft.AspNetCore.Http;\nusing Microsoft.AspNetCore.Routing;\nusing Microsoft.Extensions.DependencyInjection;\nusing Tarol.StronglyTypedId;\nnamespace Tarol.Changes.Generated;\n");
        sb.AppendLine("public static class GeneratedChangeEndpoints\n{");
        sb.AppendLine("    public static IEndpointRouteBuilder MapChanges(this IEndpointRouteBuilder app)\n    {");
        foreach (var m in models.Where(m => m.Route is not null).OrderBy(m => m.Route))
        {
            var space = m.Route!.IndexOf(' ');
            var verb = m.Route.Substring(0, space);
            var pattern = m.Route.Substring(space + 1);
            var routeMembers = m.Members.Items.Where(x => pattern.IndexOf("{" + Camel(x.Name) + "}", System.StringComparison.OrdinalIgnoreCase) >= 0).ToArray();
            var bodyNeeded = m.Members.Items.Length > routeMembers.Length;
            var map = verb switch { "PUT" => "MapPut", "DELETE" => "MapDelete", "PATCH" => "MapPatch", _ => "MapPost" };
            var auth = m.Policy is null ? "" : $".RequireAuthorization(\"{m.Policy}\")";
            if (style == "delegate")
            {
                // what a naive generator would write; the Request Delegate Generator does not see generated code
                sb.AppendLine($"        app.{map}(\"{pattern}\", static async (HttpContext http, global::Tarol.Changes.ChangePipeline pipeline) => await Run_{m.Name}(http)){auth};");
            }
            else
            {
                sb.AppendLine($"        app.{map}(\"{pattern}\", (RequestDelegate)Run_{m.Name}){auth}");
                sb.AppendLine($"           .WithMetadata(new global::Microsoft.AspNetCore.Http.Metadata.AcceptsMetadata(new[] {{ \"application/json\" }}, typeof({m.Full}), isOptional: {(bodyNeeded ? "false" : "true")}));");
            }
        }
        foreach (var g in models.SelectMany(m => m.Webhooks.Items.Select(h => (m, h))).GroupBy(x => x.h.Sender))
            sb.AppendLine($"        app.MapPost(\"/webhooks/{g.Key}\", (RequestDelegate)Webhook_{Ident(g.Key)});");
        sb.AppendLine("        return app;\n    }\n");

        foreach (var m in models.Where(m => m.Route is not null))
        {
            var pattern = m.Route!.Substring(m.Route.IndexOf(' ') + 1);
            var routeMembers = m.Members.Items.Where(x => pattern.IndexOf("{" + Camel(x.Name) + "}", System.StringComparison.OrdinalIgnoreCase) >= 0).ToArray();
            var bodyNeeded = m.Members.Items.Length > routeMembers.Length;
            sb.AppendLine($"    private static async global::System.Threading.Tasks.Task Run_{m.Name}(HttpContext http)\n    {{");
            sb.AppendLine("        var services = http.RequestServices;");
            sb.AppendLine("        var json = services.GetRequiredService<global::Tarol.Changes.Web.ChangeJson>();");
            foreach (var r in routeMembers)
            {
                sb.AppendLine($"        if (!{r.Type}.TryParse(http.Request.RouteValues[\"{Camel(r.Name)}\"] as string, null, out var route_{r.Name}))");
                sb.AppendLine($"        {{ await global::Tarol.Changes.Web.ChangeHttp.Write(http, global::Tarol.Results.Invalid.Field(\"{r.Name}\", \"Format\"), json); return; }}");
            }
            if (bodyNeeded)
            {
                sb.AppendLine($"        var body = await global::Tarol.Changes.Web.ChangeHttp.ReadBody<{m.Full}>(http, json);");
                sb.AppendLine("        if (body.Failure is { } bad) { await global::Tarol.Changes.Web.ChangeHttp.Write(http, bad, json); return; }");
                var with = string.Join(", ", routeMembers.Select(r => $"{r.Name} = route_{r.Name}"));
                sb.AppendLine($"        var input = body.Value!{(with.Length > 0 ? $" with {{ {with} }}" : "")};");
                if (m.IsCreation && m.TargetMember is { } t)
                    sb.AppendLine($"        if (input.{t} == default) input = input with {{ {t} = global::Tarol.StronglyTypedId.Id<{m.Aggregate}>.New(services.GetRequiredService<global::System.TimeProvider>()) }};");
            }
            else
                sb.AppendLine($"        var input = new {m.Full}({string.Join(", ", m.Members.Items.Select(x => $"route_{x.Name}"))});");
            sb.AppendLine("        var (context, options) = global::Tarol.Changes.Web.ChangeHttp.Context(http);");
            sb.AppendLine("        var result = await services.GetRequiredService<global::Tarol.Changes.ChangePipeline>().Run(input, context, options, http.RequestAborted);");
            sb.AppendLine($"        await global::Tarol.Changes.Web.ChangeHttp.Write(http, result, json, created: {(m.IsCreation ? "true" : "false")});\n    }}\n");
        }

        foreach (var g in models.SelectMany(m => m.Webhooks.Items.Select(h => (m, h))).GroupBy(x => x.h.Sender))
        {
            sb.AppendLine($"    private static async global::System.Threading.Tasks.Task Webhook_{Ident(g.Key)}(HttpContext http)\n    {{");
            sb.AppendLine("        var services = http.RequestServices;");
            sb.AppendLine("        var json = services.GetRequiredService<global::Tarol.Changes.Web.ChangeJson>();");
            sb.AppendLine($"        var delivery = await global::Tarol.Changes.Web.Webhooks.Read(http, \"{g.Key}\");");
            sb.AppendLine("        if (delivery.Rejected is { } status) { http.Response.StatusCode = status; return; }");
            sb.AppendLine("        var pipeline = services.GetRequiredService<global::Tarol.Changes.ChangePipeline>();");
            sb.AppendLine($"        var context = global::Tarol.Kernel.OperationContext.Start(global::Tarol.Kernel.Actor.Service(\"webhook:{g.Key}\"), global::Tarol.Options.Option.None, services.GetRequiredService<global::System.TimeProvider>());");
            sb.AppendLine("        global::Tarol.Results.Result<global::Tarol.Changes.ChangeOutcome> result;");
            sb.AppendLine("        switch (delivery.Type)\n        {");
            foreach (var (m, h) in g)
            {
                sb.AppendLine($"            case \"{h.Type}\":");
                sb.AppendLine($"                var payload_{m.Name} = global::System.Text.Json.JsonSerializer.Deserialize(delivery.Data, (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<{h.Payload}>)json.Options.GetTypeInfo(typeof({h.Payload})));");
                sb.AppendLine($"                if (payload_{m.Name} is null) {{ http.Response.StatusCode = 400; return; }}");
                sb.AppendLine($"                result = await pipeline.Run({m.Full}.{h.Method}(payload_{m.Name}), context, new global::Tarol.Changes.ChangeOptions(Key: new global::Tarol.Changes.IdempotencyKey(global::Tarol.Options.Option.None, \"{g.Key}\", delivery.Id)), http.RequestAborted);");
                sb.AppendLine("                break;");
            }
            sb.AppendLine("            default: http.Response.StatusCode = 202; return;   // a type we do not handle: acknowledge, do not make them retry\n        }");
            sb.AppendLine("        await global::Tarol.Changes.Web.Webhooks.Answer(http, result);\n    }\n");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string Camel(string s) => s.Length == 0 ? s : char.ToLowerInvariant(s[0]) + s.Substring(1);
    private static string Ident(string s) => new string(s.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());
}
