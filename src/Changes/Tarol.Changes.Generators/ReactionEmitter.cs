using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Tarol.Changes.Generators;

/// <summary>
///     Emits the public <c>GeneratedReactions</c> of an assembly: one static array per event type (a collection expression
///     in the span-returning method would be CS9203), the table, the schedule, the switch (name, event) → factory →
///     <c>ChangePipeline.Run</c>, and the <c>ReactionSet</c> over all of them. Output is ordered by names, never by input order.
/// </summary>
internal static class ReactionEmitter
{
    public static string Emit(ImmutableArray<ReactionModel> reactions, string? assemblyName)
    {
        var sorted = reactions.Sort();
        var byEvent = sorted.GroupBy(r => r.Event)
            .OrderByDescending(g => g.First().EventDepth).ThenBy(g => g.Key, System.StringComparer.Ordinal)
            .ToList();
        var names = sorted.Select(r => r.Name).Distinct(System.StringComparer.Ordinal).OrderBy(n => n, System.StringComparer.Ordinal).ToList();
        var scheduled = sorted.Where(r => r.DueAt is not null).Select(r => r.Name).Distinct(System.StringComparer.Ordinal)
            .OrderBy(n => n, System.StringComparer.Ordinal).ToList();

        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n#nullable enable\n[assembly: global::Tarol.Changes.DeclaredNames(\"reaction\"").Append(string.Concat(DeclaredNames.Of(sorted.Select(r => r.Name)))).Append(")]\n");
        sb.Append("namespace ").Append(Emitter.Namespace(assemblyName)).Append(";\n\n");
        sb.Append("/// <summary>\n/// The reactions of this assembly (<c>[OnEvent&lt;T&gt;]</c> factories): pass <see cref=\"Set\"/> to the store and the worker,\n");
        sb.Append("/// or combine it with other assemblies' sets (<see cref=\"global::Tarol.Changes.ReactionSet.Combine\"/>).\n/// </summary>\n");
        sb.Append("public static class GeneratedReactions\n{\n");
        for (var i = 0; i < byEvent.Count; i++)
        {
            sb.Append("    private static readonly string[] On").Append(i.ToString(CultureInfo.InvariantCulture)).Append(" = [");
            sb.Append(string.Join(", ", byEvent[i].Select(r => Literal(r.Name)).Distinct().OrderBy(n => n, System.StringComparer.Ordinal)));
            sb.Append("];\n");
        }
        sb.Append("    private static readonly string[] AllNames = [").Append(string.Join(", ", names.Select(Literal))).Append("];\n");
        sb.Append("    private static readonly string[] ScheduledNames = [").Append(string.Join(", ", scheduled.Select(Literal))).Append("];\n\n");

        sb.Append("    /// <summary>The reaction set of this assembly.</summary>\n");
        sb.Append("    public static global::Tarol.Changes.ReactionSet Set { get; } = new(AllNames, ReactionsTo, DueAt, ScheduledNames, React);\n\n");

        sb.Append("    /// <summary>The names of the reactions to <paramref name=\"domainEvent\"/>; empty for none.</summary>\n");
        sb.Append("    public static global::System.ReadOnlySpan<string> ReactionsTo(global::Tarol.Primitives.DomainEvent domainEvent) => domainEvent switch\n    {\n");
        for (var i = 0; i < byEvent.Count; i++)
            sb.Append("        ").Append(byEvent[i].Key).Append(" => On").Append(i.ToString(CultureInfo.InvariantCulture)).Append(",\n");
        sb.Append("        _ => global::System.ReadOnlySpan<string>.Empty,\n    };\n\n");

        sb.Append("    /// <summary>When the row of a scheduled reaction is due; <see langword=\"null\"/> = at the commit.</summary>\n");
        sb.Append("    public static global::System.DateTimeOffset? DueAt(global::Tarol.Primitives.DomainEvent domainEvent, string reaction) => (reaction, domainEvent) switch\n    {\n");
        foreach (var r in sorted.Where(r => r.DueAt is not null))
            sb.Append("        (").Append(Literal(r.Name)).Append(", ").Append(r.Event).Append(" e) => e.").Append(r.DueAt).Append(",\n");
        sb.Append("        _ => null,\n    };\n\n");

        sb.Append("    /// <summary>Maps the event to the change and runs it as the system, caused by the event, with the key (reaction, event id).</summary>\n");
        sb.Append("    /// <exception cref=\"global::System.InvalidOperationException\">No reaction of this assembly has that name for that event.</exception>\n");
        sb.Append("    public static global::System.Threading.Tasks.ValueTask<global::Tarol.Results.Result<global::Tarol.Changes.ChangeOutcome>> React(\n");
        sb.Append("        global::Tarol.Changes.ChangePipeline pipeline, string reaction, global::Tarol.Primitives.RecordedEvent recorded,\n");
        sb.Append("        global::System.Threading.CancellationToken cancellationToken)\n    {\n");
        sb.Append("        global::System.ArgumentNullException.ThrowIfNull(pipeline);\n        global::System.ArgumentNullException.ThrowIfNull(recorded);\n");
        sb.Append("        var context = global::Tarol.Changes.ReactionSet.Context(reaction, recorded);\n");
        sb.Append("        var options = global::Tarol.Changes.ReactionSet.Options(reaction, recorded);\n");
        sb.Append("        return (reaction, recorded.Event.Event) switch\n        {\n");
        foreach (var r in sorted.OrderByDescending(r => r.EventDepth).ThenBy(r => r))
        {
            sb.Append("            (").Append(Literal(r.Name)).Append(", ").Append(r.Event).Append(" e) => pipeline.Run(")
                .Append(r.Factory).Append(r.WithRecorded ? "(e, recorded)" : "(e)").Append(", context, options, cancellationToken),\n");
        }
        sb.Append("            _ => throw new global::System.InvalidOperationException($\"The reaction '{reaction}' of ")
            .Append(Interpolated(assemblyName ?? "this assembly")).Append(" does not handle {recorded.Event.Event.GetType().Name}.\"),\n");
        sb.Append("        };\n    }\n}\n");
        return sb.ToString();
    }

    private static string Literal(string value) => "\"" + Escape(value) + "\"";

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private static string Interpolated(string value) => Escape(value).Replace("{", "{{").Replace("}", "}}");
}
