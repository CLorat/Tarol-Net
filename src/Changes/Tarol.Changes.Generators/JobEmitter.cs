using System.Linq;
using System.Collections.Immutable;
using System.Text;

namespace Tarol.Changes.Generators;

/// <summary>
///     Emits the public <c>GeneratedJobs</c> of an assembly: the definitions, the switch (job name) → factory →
///     <c>ChangePipeline.Run</c> with the occurrence's context and key, and the <c>JobSet</c> over both. Ordered by names.
/// </summary>
internal static class JobEmitter
{
    private static readonly string[] Policies = ["Latest", "All", "Skip"];

    public static string Emit(ImmutableArray<JobModel> jobs, string? assemblyName)
    {
        var sorted = jobs.Sort();
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n#nullable enable\n[assembly: global::Tarol.Changes.DeclaredNames(\"job\"").Append(string.Concat(DeclaredNames.Of(jobs.Select(j => j.Name)))).Append(")]\n");
        sb.Append("namespace ").Append(Emitter.Namespace(assemblyName)).Append(";\n\n");
        sb.Append("/// <summary>\n/// The scheduled changes of this assembly (<c>[Scheduled]</c> factories): pass <see cref=\"Set\"/> to <c>AddJobs</c>,\n");
        sb.Append("/// or combine it with other assemblies' sets (<see cref=\"global::Tarol.Changes.JobSet.Combine\"/>).\n/// </summary>\n");
        sb.Append("public static class GeneratedJobs\n{\n");
        sb.Append("    private static readonly global::Tarol.Changes.JobDefinition[] Definitions =\n    [\n");
        foreach (var job in sorted)
        {
            sb.Append("        new(").Append(Literal(job.Name)).Append(", ").Append(Literal(job.Cron)).Append(", ").Append(Literal(job.TimeZone))
                .Append(", global::Tarol.Changes.Missed.").Append(Policies[job.Missed]).Append(", ").Append(job.PerTenant ? "true" : "false").Append("),\n");
        }
        sb.Append("    ];\n\n");
        sb.Append("    /// <summary>The job set of this assembly.</summary>\n");
        sb.Append("    public static global::Tarol.Changes.JobSet Set { get; } = new(Definitions, Run);\n\n");
        sb.Append("    /// <summary>Maps the occurrence to the change and runs it as the system with the key (tenant, job, occurrence).</summary>\n");
        sb.Append("    /// <exception cref=\"global::System.InvalidOperationException\">No job of this assembly has that name.</exception>\n");
        sb.Append("    public static global::System.Threading.Tasks.ValueTask<global::Tarol.Results.Result<global::Tarol.Changes.ChangeOutcome>> Run(\n");
        sb.Append("        global::Tarol.Changes.ChangePipeline pipeline, global::Tarol.Changes.JobOccurrence occurrence, global::System.TimeProvider clock,\n");
        sb.Append("        global::System.Threading.CancellationToken cancellationToken)\n    {\n");
        sb.Append("        global::System.ArgumentNullException.ThrowIfNull(pipeline);\n        global::System.ArgumentNullException.ThrowIfNull(occurrence);\n");
        sb.Append("        var context = global::Tarol.Changes.JobSet.Context(occurrence, clock);\n");
        sb.Append("        var options = global::Tarol.Changes.JobSet.Options(occurrence);\n");
        sb.Append("        return occurrence.Job switch\n        {\n");
        foreach (var job in sorted)
            sb.Append("            ").Append(Literal(job.Name)).Append(" => pipeline.Run(").Append(job.Factory).Append("(occurrence), context, options, cancellationToken),\n");
        sb.Append("            _ => throw new global::System.InvalidOperationException($\"The job '{occurrence.Job}' is not declared in ")
            .Append(Interpolated(assemblyName ?? "this assembly")).Append(".\"),\n");
        sb.Append("        };\n    }\n}\n");
        return sb.ToString();
    }

    private static string Literal(string value) => "\"" + Escape(value) + "\"";

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private static string Interpolated(string value) => Escape(value).Replace("{", "{{").Replace("}", "}}");
}
