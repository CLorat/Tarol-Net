using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace Tarol.Changes.Generators;

internal static class Emitter
{
    public static string Change(ChangeModel model)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n#nullable enable\n");
        if (model.Namespace is not null)
            sb.Append("namespace ").Append(model.Namespace).Append(";\n");
        sb.Append('\n');
        var indent = "";
        foreach (var containing in model.ContainingTypes)
        {
            sb.Append(indent).Append(containing).Append('\n').Append(indent).Append("{\n");
            indent += "    ";
        }
        sb.Append(indent).Append(model.Declaration).Append(' ').Append(model.Name);
        if (!model.Reads.IsEmpty)
            sb.Append(" : global::Tarol.Changes.IHasReads");
        sb.Append('\n').Append(indent).Append("{\n");
        var body = indent + "    ";
        if (model.TargetMember is "")
        {
            sb.Append(body).Append("/// <summary>Not read: <c>").Append(model.Aggregate.Substring(model.Aggregate.LastIndexOf('.') + 1))
                .Append("</c> is [PerTenant], the pipeline loads the caller's tenant's one.</summary>\n");
            sb.Append(body).Append("global::Tarol.StronglyTypedId.Id<").Append(model.Aggregate).Append("> global::Tarol.Changes.IChange<")
                .Append(model.Aggregate).Append(">.Target => global::Tarol.StronglyTypedId.Id<").Append(model.Aggregate).Append(">.Empty;\n");
        }
        else if (model.TargetMember is { } target)
        {
            sb.Append(body).Append("/// <summary>The aggregate the pipeline loads: <see cref=\"").Append(target).Append("\"/>.</summary>\n");
            sb.Append(body).Append("global::Tarol.StronglyTypedId.Id<").Append(model.Aggregate).Append("> global::Tarol.Changes.IChange<")
                .Append(model.Aggregate).Append(">.Target => this.").Append(target).Append(";\n");
        }
        if (!model.Reads.IsEmpty)
        {
            if (model.TargetMember is not null)
                sb.Append('\n');
            sb.Append(body).Append("async global::System.Threading.Tasks.ValueTask<global::Tarol.Results.Result<global::Tarol.Changes.Reads>> global::Tarol.Changes.IHasReads.LoadReads(\n");
            sb.Append(body).Append("    global::Tarol.Persistence.IAggregateReader reader, global::Tarol.Kernel.OperationContext context, global::System.Threading.CancellationToken cancellationToken)\n");
            sb.Append(body).Append("{\n");
            sb.Append(body).Append("    var loaded = new global::System.Collections.Generic.Dictionary<string, object>(").Append(model.Reads.Count).Append(");\n");
            var i = 0;
            foreach (var read in model.Reads)
            {
                var n = i.ToString(System.Globalization.CultureInfo.InvariantCulture);
                var missing = read.Optional ? "{ }"
                    : "return global::Tarol.Results.Error.UnprocessableEntity(\"" + read.AggregateName + ".NotFound\", \"" + read.Key + "\");";
                if (read.IdExpression is null)
                {
                    // [Reads<T>] of a [PerTenant] aggregate (TN-40): the caller's tenant's one
                    sb.Append(body).Append("    if (!global::Tarol.Changes.TenantAggregates.TryIdOf<").Append(read.Aggregate).Append(">(context, out var __id").Append(n).Append("))\n");
                    sb.Append(body).Append("        ").Append(read.Optional ? "{ }" : missing).Append('\n');
                    sb.Append(body).Append("    else if (!(await reader.Load(__id").Append(n).Append(", context, cancellationToken)).TryGetValue(out ")
                        .Append(read.Aggregate).Append("? __read").Append(n).Append("))\n");
                }
                else
                {
                    sb.Append(body).Append("    if (!(await reader.Load(").Append(read.IdExpression).Append(", context, cancellationToken)).TryGetValue(out ")
                        .Append(read.Aggregate).Append("? __read").Append(n).Append("))\n");
                }
                sb.Append(body).Append("        ").Append(missing).Append('\n');
                sb.Append(body).Append("    else\n");
                sb.Append(body).Append("        loaded[\"").Append(read.Key).Append("\"] = __read").Append(n).Append(";\n");
                i++;
            }
            sb.Append(body).Append("    return new global::Tarol.Changes.Reads(loaded);\n");
            sb.Append(body).Append("}\n");
        }
        sb.Append(indent).Append("}\n");
        for (var level = model.ContainingTypes.Count - 1; level >= 0; level--)
            sb.Append(' ', level * 4).Append("}\n");
        return sb.ToString();
    }

    public static string Dispatch(ImmutableArray<DispatchEntry> models, string? assemblyName)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n#nullable enable\nnamespace ").Append(Namespace(assemblyName)).Append(";\n\n");
        sb.Append("/// <summary>The changes of this assembly as one typed entry: an <see cref=\"object\"/> (a saga outbox row, a test) to its <c>Run</c>, without reflection.</summary>\n");
        sb.Append("internal static class GeneratedChanges\n{\n");
        sb.Append("    /// <summary>Runs <paramref name=\"change\"/> through <paramref name=\"pipeline\"/> by its type.</summary>\n");
        sb.Append("    /// <exception cref=\"global::System.ArgumentException\"><paramref name=\"change\"/> is not a change of this assembly.</exception>\n");
        sb.Append("    public static global::System.Threading.Tasks.ValueTask<global::Tarol.Results.Result<global::Tarol.Changes.ChangeOutcome>> Dispatch(\n");
        sb.Append("        this global::Tarol.Changes.ChangePipeline pipeline, object change, global::Tarol.Kernel.OperationContext context,\n");
        sb.Append("        global::Tarol.Changes.ChangeOptions options = default, global::System.Threading.CancellationToken cancellationToken = default)\n");
        sb.Append("    {\n        global::System.ArgumentNullException.ThrowIfNull(pipeline);\n        return change switch\n        {\n");
        foreach (var model in models.OrderByDescending(m => m.Depth).ThenBy(m => m.FullName, System.StringComparer.Ordinal))
            sb.Append("            ").Append(model.FullName).Append(" c => pipeline.Run(c, context, options, cancellationToken),\n");
        sb.Append("            null => throw new global::System.ArgumentNullException(nameof(change)),\n");
        sb.Append("            _ => throw new global::System.ArgumentException($\"{change.GetType().Name} is not a change of ")
            .Append(assemblyName ?? "this assembly").Append(".\", nameof(change)),\n");
        sb.Append("        };\n    }\n}\n");
        return sb.ToString();
    }

    public static string Namespace(string? assemblyName)
    {
        if (string.IsNullOrWhiteSpace(assemblyName))
            return "Tarol.Changes.Generated";
        var parts = new List<string>();
        foreach (var part in assemblyName!.Split('.'))
        {
            var chars = part.Select(c => char.IsLetterOrDigit(c) || c == '_' ? c : '_').ToArray();
            var name = new string(chars);
            if (name.Length == 0 || char.IsDigit(name[0]))
                name = "_" + name;
            parts.Add(name);
        }
        return string.Join(".", parts);
    }

    public static string HintName(ChangeModel model)
        => (model.Namespace is null ? "" : model.Namespace + ".")
           + string.Concat(model.ContainingTypes.Select(c => c.Substring(c.LastIndexOf(' ') + 1) + "."))
           + model.Name + ".Change.g.cs";
}
