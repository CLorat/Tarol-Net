using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Tarol.Messaging.Generators;

/// <summary>
///     Emits the public <c>GeneratedConsumers</c> of an assembly: one static topic array per consumer, the
///     <c>ConsumerSet</c>, and the switch (consumer, contract, version) → payload → factory → <c>ChangePipeline.Run</c>; a
///     known contract in another version is <c>UnknownVersion</c>, anything else <c>UnknownContract</c>. Ordered by names.
/// </summary>
internal static class Emitter
{
    public static string Consumers(ImmutableArray<ConsumerModel> consumers, string? assemblyName)
    {
        var byName = consumers.GroupBy(c => c.Name).OrderBy(g => g.Key, System.StringComparer.Ordinal).ToList();
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n#nullable enable\nnamespace ").Append(Namespace(assemblyName)).Append(";\n\n");
        sb.Append("/// <summary>\n/// The consumers of this assembly (<c>[Consumes]</c> factories): pass <see cref=\"Set\"/> to <c>AddMessaging(…).Consume(…)</c>,\n");
        sb.Append("/// or combine it with other assemblies' sets (<see cref=\"global::Tarol.Messaging.ConsumerSet.Combine\"/>).\n/// </summary>\n");
        sb.Append("[global::System.CodeDom.Compiler.GeneratedCode(\"Tarol.Messaging.Generators\", \"1.0\")]\n");
        sb.Append("public static class GeneratedConsumers\n{\n");
        for (var i = 0; i < byName.Count; i++)
        {
            var topics = byName[i].Select(c => c.Contract).Distinct().OrderBy(t => t, System.StringComparer.Ordinal);
            sb.Append("    private static readonly string[] Topics").Append(i.ToString(CultureInfo.InvariantCulture)).Append(" = { ")
                .Append(string.Join(", ", topics.Select(Literal))).Append(" };\n");
        }
        sb.Append("\n    /// <summary>The consumer set of this assembly.</summary>\n");
        sb.Append("    public static global::Tarol.Messaging.ConsumerSet Set { get; } = new(new global::Tarol.Messaging.ConsumerInfo[]\n    {\n");
        for (var i = 0; i < byName.Count; i++)
            sb.Append("        new(").Append(Literal(byName[i].Key)).Append(", Topics").Append(i.ToString(CultureInfo.InvariantCulture)).Append("),\n");
        sb.Append("    }, Run);\n\n");

        sb.Append("    private static async global::System.Threading.Tasks.ValueTask<global::Tarol.Messaging.ConsumerRun> Run(string consumer,\n");
        sb.Append("        global::Tarol.Changes.ChangePipeline pipeline, global::Tarol.Messaging.Message message, global::Tarol.Messaging.MessageScope scope,\n");
        sb.Append("        global::System.Threading.CancellationToken cancellationToken)\n    {\n");
        sb.Append("        switch (consumer, message.Type, message.Version)\n        {\n");
        var payload = 0;
        foreach (var group in byName)
        {
            foreach (var model in group.OrderBy(c => c.Contract, System.StringComparer.Ordinal).ThenBy(c => c.Version))
            {
                var local = "payload" + (payload++).ToString(CultureInfo.InvariantCulture);
                sb.Append("            case (").Append(Literal(model.Name)).Append(", ").Append(Literal(model.Contract)).Append(", ")
                    .Append(model.Version.ToString(CultureInfo.InvariantCulture)).Append("):\n            {\n");
                sb.Append("                var ").Append(local).Append(" = scope.Payload<").Append(model.Payload).Append(">(message.Data);\n");
                sb.Append("                if (").Append(local).Append(" is null)\n");
                sb.Append("                    return global::Tarol.Messaging.ConsumerRun.Not(global::Tarol.Messaging.Mapped.Malformed);   // the data does not match its contract\n");
                sb.Append("                return new(global::Tarol.Messaging.Mapped.Ran, await pipeline.Run(").Append(model.Change).Append('.').Append(model.Method)
                    .Append('(').Append(local).Append(model.TakesMessage ? ", message" : "").Append("), scope.Operation, scope.Options, cancellationToken)")
                    .Append(".ConfigureAwait(false));\n            }\n");
            }
            foreach (var contract in group.Select(c => c.Contract).Distinct().OrderBy(c => c, System.StringComparer.Ordinal))
                sb.Append("            case (").Append(Literal(group.Key)).Append(", ").Append(Literal(contract))
                    .Append(", _):\n                return global::Tarol.Messaging.ConsumerRun.Not(global::Tarol.Messaging.Mapped.UnknownVersion);   // a known contract, another version (R-10)\n");
        }
        sb.Append("            default:\n                return global::Tarol.Messaging.ConsumerRun.Not(global::Tarol.Messaging.Mapped.UnknownContract);\n");
        sb.Append("        }\n    }\n}\n");
        return sb.ToString();
    }

    /// <summary>
    ///     The public <c>GeneratedPublications</c>: one constant per row name, one static array per event type (derived events
    ///     first, each with its base types' publications: a collection expression in the span-returning table would be
    ///     CS9203), the <c>PublicationSet</c>, and the map (row, event) → mapping method → the application's JSON.
    /// </summary>
    public static string Publications(ImmutableArray<PublicationModel> publications, string? assemblyName)
    {
        var sorted = publications.OrderBy(p => p.Contract, System.StringComparer.Ordinal).ThenBy(p => p.Version).ToList();
        var constant = new Dictionary<string, string>();
        for (var i = 0; i < sorted.Count; i++)
            constant[sorted[i].Name] = "P" + i.ToString(CultureInfo.InvariantCulture);
        var events = sorted.GroupBy(p => p.Event).Select(g => (Event: g.Key, Depth: g.First().EventBases.Count))
            .OrderByDescending(e => e.Depth).ThenBy(e => e.Event, System.StringComparer.Ordinal).ToList();

        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n#nullable enable\nnamespace ").Append(Namespace(assemblyName)).Append(";\n\n");
        sb.Append("/// <summary>\n/// The publications of this assembly (<c>[Publishes&lt;T&gt;]</c> methods): pass <see cref=\"Set\"/> to <c>AddMessaging(…).Publish(…)</c>,\n");
        sb.Append("/// or combine it with other assemblies' sets (<see cref=\"global::Tarol.Messaging.PublicationSet.Combine\"/>).\n/// </summary>\n");
        sb.Append("[global::System.CodeDom.Compiler.GeneratedCode(\"Tarol.Messaging.Generators\", \"1.0\")]\n");
        sb.Append("public static class GeneratedPublications\n{\n");
        foreach (var p in sorted)
            sb.Append("    private const string ").Append(constant[p.Name]).Append(" = ").Append(Literal(p.Name)).Append(";\n");
        for (var i = 0; i < events.Count; i++)
        {
            var e = events[i];
            var rows = sorted.Where(p => p.Event == e.Event || sorted.First(q => q.Event == e.Event).EventBases.Contains(p.Event)).Select(p => constant[p.Name]);
            sb.Append("    private static readonly string[] On").Append(i.ToString(CultureInfo.InvariantCulture)).Append(" = { ")
                .Append(string.Join(", ", rows)).Append(" };\n");
        }
        sb.Append("\n    private static readonly global::Tarol.Messaging.PublicationInfo[] All =\n    {\n");
        foreach (var p in sorted)
        {
            sb.Append("        new(").Append(constant[p.Name]).Append(", ").Append(Literal(p.Contract)).Append(", ")
                .Append(p.Version.ToString(CultureInfo.InvariantCulture)).Append(") { ContractType = typeof(").Append(p.Record).Append("), EventType = typeof(")
                .Append(p.Event).Append(')');
            if (p.Stream is not null)
                sb.Append(", Stream = ").Append(Literal(p.Stream));
            sb.Append(" },\n");
        }
        sb.Append("    };\n\n");
        sb.Append("    /// <summary>The publication set of this assembly.</summary>\n");
        sb.Append("    public static global::Tarol.Messaging.PublicationSet Set { get; } = new(All, Rows, Map);\n\n");

        sb.Append("    /// <summary>The publication rows of <paramref name=\"domainEvent\"/>; empty for none.</summary>\n");
        sb.Append("    public static global::System.ReadOnlySpan<string> Rows(global::Tarol.Primitives.DomainEvent domainEvent) => domainEvent switch\n    {\n");
        for (var i = 0; i < events.Count; i++)
            sb.Append("        ").Append(events[i].Event).Append(" => On").Append(i.ToString(CultureInfo.InvariantCulture)).Append(",\n");
        sb.Append("        _ => global::System.ReadOnlySpan<string>.Empty,\n    };\n\n");

        sb.Append("    private static byte[]? Map(string publication, global::Tarol.Primitives.RecordedEvent recorded, global::System.Text.Json.JsonSerializerOptions json)\n");
        sb.Append("        => (publication, recorded.Event.Event) switch\n        {\n");
        foreach (var p in sorted)
            sb.Append("            (").Append(constant[p.Name]).Append(", ").Append(p.Event).Append(" e) => global::Tarol.Messaging.PublicationSet.Serialize<").Append(p.Record)
                .Append(">(").Append(p.Type).Append('.').Append(p.Method).Append(p.TakesRecorded ? "(e, recorded)" : "(e)").Append(", json),\n");
        sb.Append("            _ => throw new global::System.InvalidOperationException($\"The publication '{publication}' does not map {recorded.Event.Event.GetType().Name}.\"),\n");
        sb.Append("        };\n}\n");
        return sb.ToString();
    }

    public static string Namespace(string? assemblyName)
    {
        if (string.IsNullOrWhiteSpace(assemblyName))
            return "Tarol.Messaging.Generated";
        var parts = new List<string>();
        foreach (var part in assemblyName!.Split('.'))
        {
            var name = new string(part.Select(c => char.IsLetterOrDigit(c) || c == '_' ? c : '_').ToArray());
            if (name.Length == 0 || char.IsDigit(name[0]))
                name = "_" + name;
            parts.Add(name);
        }
        return string.Join(".", parts);
    }

    private static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
