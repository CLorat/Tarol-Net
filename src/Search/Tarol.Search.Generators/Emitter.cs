using System.Linq;
using System.Text;

namespace Tarol.Search.Generators;

/// <summary>Emits the explicit <c>ISearchable&lt;T&gt;</c> implementation of a searchable aggregate.</summary>
internal static class Emitter
{
    public static string Searchable(SearchModel model)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n#nullable enable\n");
        if (model.Namespace is not null)
            sb.Append("namespace ").Append(model.Namespace).Append(";\n");
        sb.Append('\n');
        var indent = "";
        foreach (var containing in model.ContainingTypes)
        {
            sb.Append(indent).Append(containing).Append('\n').Append(indent).Append("{\n");
            indent += "    ";
        }
        var root = model.FullName;
        var face = "global::Tarol.Search.ISearchable<" + root + ">";
        sb.Append(indent).Append("partial class ").Append(model.Name).Append(" : ").Append(face).Append('\n');
        sb.Append(indent).Append("{\n");
        var b = indent + "    ";

        sb.Append(b).Append("static global::Tarol.Search.SearchShape ").Append(face).Append(".Shape { get; } =\n")
            .Append(b).Append("    global::Tarol.Search.SearchShape.Of<").Append(root).Append(">(").Append(Literal(model.Label)).Append(", ")
            .Append(Literal(model.Fingerprint));
        foreach (var (suffix, label) in Flatten(model.Entities, ""))
            sb.Append(", (").Append(Literal(suffix)).Append(", ").Append(Literal(label)).Append(')');
        sb.Append(");\n\n");

        sb.Append(b).Append("static void ").Append(face).Append(".Documents(").Append(root)
            .Append(" aggregate, global::System.Collections.Generic.ICollection<global::Tarol.Search.SearchDocument> into)\n");
        sb.Append(b).Append("{\n");
        var c = b + "    ";
        sb.Append(c).Append("var type = global::Tarol.Search.SearchDocuments.StreamTypeOf<").Append(root).Append(">();\n");
        sb.Append(c).Append("var id = aggregate.Id.Value;\n");
        sb.Append(c).Append("var audience = ").Append(Audience(model)).Append(";\n");
        sb.Append(c).Append("var language = ").Append(model.Language is null ? "(string?)null" : "aggregate." + model.Language).Append(";\n");
        var title = model.Members.FirstOrDefault(static m => m.Title);
        sb.Append(c).Append("var title = ").Append(title is null ? "\"\"" : Value("aggregate", title) + " ?? \"\"").Append(";\n");
        Document(sb, c, "type", "id", "title", "aggregate", model.Members);
        var counter = 0;
        Children(sb, c, model.Entities, "aggregate", "", ref counter);
        sb.Append(b).Append("}\n");
        sb.Append(indent).Append("}\n");
        foreach (var _ in model.ContainingTypes)
        {
            indent = indent.Substring(4);
            sb.Append(indent).Append("}\n");
        }
        return sb.ToString();
    }

    private static System.Collections.Generic.IEnumerable<(string Suffix, string Label)> Flatten(EquatableArray<EntityModel> entities, string prefix)
    {
        foreach (var e in entities)
        {
            var suffix = prefix + e.Suffix;
            if (!e.Members.IsEmpty)
                yield return (suffix, e.Label);
            foreach (var child in Flatten(e.Children, suffix + "."))
                yield return child;
        }
    }

    // every entity variable gets its own number: a pattern variable of an 'if' is in scope for the rest of the method
    private static void Children(StringBuilder sb, string indent, EquatableArray<EntityModel> entities, string parent, string prefix, ref int counter)
    {
        foreach (var e in entities)
        {
            var v = "e" + (counter++).ToString(System.Globalization.CultureInfo.InvariantCulture);
            var suffix = prefix + e.Suffix;
            if (e.IsSet)
                sb.Append(indent).Append("foreach (var ").Append(v).Append(" in ").Append(parent).Append('.').Append(e.Property).Append(")\n");
            else
                sb.Append(indent).Append("if (").Append(parent).Append('.').Append(e.Property).Append(".Value is { } ").Append(v).Append(")\n");
            sb.Append(indent).Append("{\n");
            var inner = indent + "    ";
            if (!e.Members.IsEmpty)
            {
                var title = e.Members.FirstOrDefault(static m => m.Title);
                Document(sb, inner, "type + " + Literal("." + suffix), v + ".Id.Value",
                    title is null ? "title" : "(" + Value(v, title) + " ?? title)", v, e.Members);
            }
            Children(sb, inner, e.Children, v, suffix + ".", ref counter);
            sb.Append(indent).Append("}\n");
        }
    }

    private static void Document(StringBuilder sb, string indent, string type, string id, string title, string source, EquatableArray<MemberModel> members)
    {
        sb.Append(indent).Append("into.Add(new global::Tarol.Search.SearchDocument(").Append(type).Append(", ").Append(id).Append(", id, ").Append(title).Append(")\n");
        sb.Append(indent).Append("{\n");
        var i = indent + "    ";
        for (var w = 0; w < 4; w++)
        {
            var texts = members.Where(m => m.Weight == w && !m.Exact).ToList();
            if (texts.Count == 0)
                continue;
            sb.Append(i).Append((char)('A' + w)).Append(" = global::Tarol.Search.SearchDocuments.Join(new string?[] { ")
                .Append(string.Join(", ", texts.Select(m => Value(source, m)))).Append(" }),\n");
        }
        var exact = members.Where(static m => m.Exact).ToList();
        if (exact.Count > 0)
            sb.Append(i).Append("Exact = global::Tarol.Search.SearchDocuments.Exact(new string?[] { ")
                .Append(string.Join(", ", exact.Select(m => Value(source, m)))).Append(" }),\n");
        sb.Append(i).Append("Audience = audience,\n");
        sb.Append(i).Append("Language = language,\n");
        sb.Append(indent).Append("});\n");
    }

    private static string Value(string source, MemberModel m) => m.Kind switch
    {
        ValueKind.String => source + "." + m.Name,
        ValueKind.Strings => "global::Tarol.Search.SearchDocuments.Text(" + source + "." + m.Name + ")",
        ValueKind.NullableFormatted => source + "." + m.Name + "?.ToString()",
        _ => source + "." + m.Name + ".ToString()",
    };

    private static string Audience(SearchModel model) => model.Audience is null
        ? "global::System.Array.Empty<string>()"
        : model.AudienceKind switch
        {
            ValueKind.String => "global::Tarol.Search.SearchDocuments.Audience(new string?[] { aggregate." + model.Audience + " })",
            ValueKind.Guid => "global::Tarol.Search.SearchDocuments.Audience(new string?[] { aggregate." + model.Audience + ".ToString() })",
            ValueKind.Strings => "global::Tarol.Search.SearchDocuments.Audience(aggregate." + model.Audience + ")",
            _ => "global::Tarol.Search.SearchDocuments.Audience(global::System.Linq.Enumerable.Select(aggregate." + model.Audience + ", static g => (string?)g.ToString()))",
        };

    private static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
