using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace Tarol.Primitives.Generators;

/// <summary>Writes <c>&lt;Enum&gt;Lifecycle</c> for one valid <c>[Lifecycle]</c> enum: edge table, guards and Mermaid diagram.</summary>
internal static class LifecycleEmitter
{
    private const string Result = "global::Tarol.Results.Result";
    private const string Error = "global::Tarol.Results.Error";

    /// <summary>The Mermaid <c>stateDiagram-v2</c>: initial state, every edge (labelled with its <c>[Transition]</c> events), terminal states.</summary>
    public static string Diagram(LifecycleModel m)
    {
        var sb = new StringBuilder("stateDiagram-v2\n    [*] --> ").Append(m.Initial).Append('\n');
        foreach (var edge in m.Edges)
        {
            sb.Append("    ").Append(edge.From).Append(" --> ").Append(edge.To);
            var labels = m.Labels.Where(l => l.From == edge.From && l.To == edge.To).Select(static l => l.Event)
                .Distinct().OrderBy(static e => e, System.StringComparer.Ordinal).ToList();
            if (labels.Count > 0)
                sb.Append(" : ").Append(string.Join(", ", labels));
            sb.Append('\n');
        }

        foreach (var state in m.States.Where(s => m.Edges.All(e => e.From != s)))
            sb.Append("    ").Append(state).Append(" --> [*]\n");
        return sb.ToString();
    }

    public static string Emit(LifecycleModel m)
    {
        var t = m.FullName;
        var outgoing = m.States.ToDictionary(s => s, s => m.Edges.Where(e => e.From == s).Select(e => e.To).ToList());
        var diagram = Diagram(m);

        var sb = new StringBuilder("// <auto-generated/>\n#nullable enable\n\n");
        if (m.Namespace is not null)
            sb.Append("namespace ").Append(m.Namespace).Append(";\n\n");
        sb.Append("/// <summary>The lifecycle of <see cref=\"").Append(t.Replace("global::", "")).Append("\"/>: its edges, guards and diagram.</summary>\n");
        sb.Append("/// <remarks><code>\n");
        foreach (var line in diagram.TrimEnd('\n').Split('\n'))
            sb.Append("/// ").Append(line.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;")).Append('\n');
        sb.Append("/// </code></remarks>\n");
        sb.Append(m.Accessibility).Append(" static class ").Append(m.Class).Append("\n{\n");
        sb.Append("    /// <summary>The initial state: a created root or entity must be in it after its creation event.</summary>\n");
        sb.Append("    public const ").Append(t).Append(" Initial = ").Append(t).Append('.').Append(m.Initial).Append(";\n\n");
        sb.Append("    /// <summary>The lifecycle as a Mermaid state diagram (edges labelled with their <c>[Transition]</c> events).</summary>\n");
        sb.Append("    public const string Diagram = ").Append(SymbolDisplay.FormatLiteral(diagram, true)).Append(";\n\n");
        sb.Append("    /// <summary>True when <paramref name=\"to\"/> is a declared edge from <paramref name=\"from\"/>.</summary>\n");
        sb.Append("    /// <param name=\"from\">The current state.</param>\n");
        sb.Append("    /// <param name=\"to\">The next state.</param>\n");
        sb.Append("    /// <returns>Whether the step is allowed.</returns>\n");
        sb.Append("    public static bool IsEdge(").Append(t).Append(" from, ").Append(t).Append(" to) => from switch\n    {\n");
        foreach (var state in m.States.Where(s => outgoing[s].Count > 0))
            sb.Append("        ").Append(t).Append('.').Append(state).Append(" => to is ")
                .Append(string.Join(" or ", outgoing[state].Select(x => t + "." + x))).Append(",\n");
        sb.Append("        _ => false,\n    };\n\n");
        var terminals = m.States.Where(s => outgoing[s].Count == 0).Select(x => t + "." + x).ToList();
        sb.Append("    /// <summary>True when the state has no outgoing edge.</summary>\n");
        sb.Append("    /// <param name=\"state\">The state.</param>\n");
        sb.Append("    /// <returns>Whether it is terminal.</returns>\n");
        sb.Append("    public static bool IsTerminal(").Append(t).Append(" state) => ")
            .Append(terminals.Count == 0 ? "false" : "state is " + string.Join(" or ", terminals)).Append(";\n\n");
        sb.Append("    /// <summary>The declared edges, in declaration order (for tests and documentation).</summary>\n");
        sb.Append("    public static global::System.ReadOnlySpan<(").Append(t).Append(" From, ").Append(t).Append(" To)> Edges => s_edges;\n\n");
        sb.Append("    private static readonly (").Append(t).Append(" From, ").Append(t).Append(" To)[] s_edges =\n    [\n");
        foreach (var e in m.Edges)
            sb.Append("        (").Append(t).Append('.').Append(e.From).Append(", ").Append(t).Append('.').Append(e.To).Append("),\n");
        sb.Append("    ];\n\n");
        sb.Append("    extension(").Append(t).Append(" state)\n    {\n");
        sb.Append("        /// <summary>True when this state may change to <paramref name=\"to\"/> (a declared edge).</summary>\n");
        sb.Append("        /// <param name=\"to\">The next state.</param>\n");
        sb.Append("        /// <returns>Whether the step is allowed.</returns>\n");
        sb.Append("        public bool CanTransitionTo(").Append(t).Append(" to) => IsEdge(state, to);\n\n");
        sb.Append("        /// <summary>Success when this state may change to <paramref name=\"to\"/>; otherwise <c>Error.Conflict(\"")
            .Append(m.Name).Append(".NotAllowed\", \"&lt;From&gt; -&gt; &lt;To&gt;\")</c>.</summary>\n");
        sb.Append("        /// <param name=\"to\">The next state.</param>\n");
        sb.Append("        /// <returns>Success, or the conflict.</returns>\n");
        sb.Append("        public ").Append(Result).Append(" RequireTransitionTo(").Append(t).Append(" to) => IsEdge(state, to)\n");
        sb.Append("            ? ").Append(Result).Append(".Success()\n");
        sb.Append("            : ").Append(Error).Append(".Conflict(\"").Append(m.Name).Append(".NotAllowed\", state.ToString() + \" -> \" + to.ToString());\n");
        sb.Append("    }\n}\n");
        return sb.ToString();
    }
}
